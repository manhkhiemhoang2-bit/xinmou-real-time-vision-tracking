//==============================================================================
// ext_ctrl.v —— 把 alg_top 的检测结果变成板载 LED / 蜂鸣器的外部控制信号
//
//  赛题扩展要求 2.4(3)：「根据视频识别结果实现外部控制」。
//  本模块只吃 alg_top 的**帧级统计**（bbox / bbox_valid / pix_count）和一路帧同步脉冲，
//  输出两路**慢速**外部控制：
//
//    O_led[3:0]  1-of-4 象限指示：目标包围盒中心落在画面哪个象限，就点亮哪一只 LED。
//                  bit0 = 左上   (cx <  W/2 且 cy <  H/2)
//                  bit1 = 右上   (cx >= W/2 且 cy <  H/2)
//                  bit2 = 左下   (cx <  W/2 且 cy >= H/2)
//                  bit3 = 右下   (cx >= W/2 且 cy >= H/2)
//                无目标（见 §二）→ 四灯全灭（0000）。
//                高有效：1 = 点亮（⚠ 板上 LED 是高有效还是低有效需上板确认）。
//
//    O_buzzer    有目标时限幅鸣叫，完整语义见 §一。
//
//  ---------------------------------------------------------------------------
//  【一、O_buzzer 的完整语义（v2，2026-09-17 修订）】
//    ① 无 → 有（重新检出）：**立刻**响一次 —— 帧同步脉冲之后 2 拍就起包络。
//    ② 持续有目标：此后每 BEEP_GAP_FRAMES 帧再响一次（默认 20 帧）。
//    ③ 每次响 = 一个 BEEP_ON_CYCLES 拍的包络（默认 400000 拍 = 6.67ms @60MHz）。
//    ④ 包络**真·不可重触发**：包络进行中到达的请求一律**丢弃**（既不重装计数器，
//       也不延长包络）⇒ 任何一段连续鸣叫的长度恒等于 BEEP_ON_CYCLES，与帧周期无关；
//       帧率再高也不会退化成常鸣。
//    ⑤ 目标消失（bbox_valid=0 / pix_count<MIN_PIX / 倒置框，见 §二）或复位：立刻静音。
//    ⇒ 检测抖动（valid 时有时无）时，每次"重新检出"都会请求一次 beep；
//      实际听感节奏的下限就是"一个包络"（6.67ms），既不会被永久静音，也不会常鸣。
//    ⚠ v1（2026-09-17 上午那版）有两条已被对抗性审查证伪的缺陷，v2 修掉：
//      · 抖动时**永不响**：v1 要连续 BEEP_GAP_FRAMES 个有效帧才响第一次
//        （审查实验 E3：1:1 抖动 60 帧，beep 数 = 0）；
//      · 包络**可被重装**：v1 的 `else if (r_beep_req)` 是重装计数器而非丢弃，
//        当 帧周期 × BEEP_GAP_FRAMES < BEEP_ON_CYCLES 时退化成常鸣
//        （E2：P=100 拍/帧 → 单段 on 2497999 拍 = 99.92%；E4：P=15000 → 2199999 拍）。
//  ---------------------------------------------------------------------------
//  【二、"有目标"的判据（三条全满足才算有目标）】
//    ① I_bbox_valid = 1
//    ② I_pix_count >= MIN_PIX
//    ③ 包围盒不倒置：I_bbox_x0 <= I_bbox_x1 且 I_bbox_y0 <= I_bbox_y1
//    第 ③ 条是**独立保护**：倒置框（min>max）没有物理意义，照算术中点解象限会指到
//    一个毫不相干的象限。alg_top / alg_color_detect_96 目前用"哨兵 bbox + valid=0"
//    兜住了这种情况，但 M6（帧差/运动）档的 bbox 来源不同、且并行工作流正在改 alg_top，
//    所以这里不再依赖上游：倒置框一律按"无目标"处理（LED 全灭、不触发 beep）。
//    ⚠ 只判"倒置"，不判"越界"：坐标超出画面（如哨兵 2047）**不算**倒置，仍按算术
//      中心解象限 —— 有意为之，以免与上游的哨兵约定打架。
//  ---------------------------------------------------------------------------
//  【三、I_frame 的口径（重要）】
//    I_frame 要接**每帧恰好 1 拍**的帧首脉冲（板级接 isp_top 的 O_tuser）。
//    本模块只用到它"每帧一次"这一个属性，与它相对 tvalid/tdata 的相位无关 ——
//    所以上游 96→128 / OSD 流水线以后再调，这里不必跟着改。
//    ⚠ 但不要自己拿 O_tuser & O_tvalid 去造脉冲：板级 data_96bit_to_128bit
//      （2026-09-17 核对，该文件自 2025-12-25 起未动）里
//      O_128b_frame_start = I_96b_frame_start 的 1 级寄存器复制，而 O_128b_valid
//      由 S_cnt 状态机产生（首拍要 2 级），两者相差 1 拍 —— 相与之后恒为 0，
//      帧同步会整条失效。
//    本模块内部对 I_frame 再做一次上升沿检测，即使上游给的是多拍电平，也只认一次。
//  ---------------------------------------------------------------------------
//  【四、为什么要"逐帧锁存"】
//    bbox 是帧级状态，换值时刻与各路视频流水线的对齐没有保证；若在像素流上实时解象限，
//    同一帧内 LED 可能先亮一个错误的象限再跳回来。所以本模块在**帧同步脉冲**那一拍把
//    bbox / valid / pix_count 整体抄进自己的寄存器，此后象限译码只读这份锁存值 ——
//    一帧之内 LED 恒定（已由对抗性审查实验 E1 独立复核：24 帧帧内变化次数全 0）。
//    时序：帧同步拍 C 锁存 → C+1 末按新值译码 → **C+2 拍起 O_led 反映新象限**。
//  ---------------------------------------------------------------------------
//  【五、象限边界与中心取整】
//    中心 = (min + max) >> 1（**向下取整**），与分界比较用**严格小于**：
//        w_left = (cx < W/2)        w_top = (cy < H/2)
//    这套"floor + 严格小于"与"用真实中心（可能带 .5）比较"**完全等价**，不是取整伪影：
//      设 s = x0+x1（整数），真实中心 s/2 < W/2 ⟺ s < W。
//      · s 为偶数：floor(s/2) = s/2，两式同；
//      · s 为奇数：s/2 是半整数、与整数 W/2 不可能相等，故
//        floor(s/2) < W/2 ⟺ s/2 < W/2 + 0.5 ⟺ s/2 < W/2。
//    例：全画面框 (0,0)-(1279,719) 的真实中心是 (639.5, 359.5)，确实落在左上象限，
//    所以点亮 LED0 是**正确**结果（不是"被 floor 吃掉"）。
//    中心正好落在分界线上（cx 恰 640 / cy 恰 360）判为**右 / 下**（严格小于的必然结果）。
//  ---------------------------------------------------------------------------
//  【六、面积与关键路径代价（估算，未跑 TD）】
//    · 本模块不在像素通路上：输入是 alg_top 的寄存器输出，输出只进 LED/蜂鸣器引脚，
//      与视频通路的关键路径无耦合（改前全芯片 slack 3.342ns，本模块不参与）。
//    · 内部最长组合链 = 12 位加法 → 取 bit[11:1] → 11 位比较 → 打一拍，只在帧率上跑。
//    · v1 → v2 的 LUT 增量估算（按每 2 位 1 个 LUT4 手估）：
//        倒置框判据 2×(11 位大小比较)          ≈ +22 LUT
//        "上一帧有目标"寄存器 + 上升沿项        ≈ +1 FF / +2 LUT
//        包络门控 !r_beep_on                    ≈ +1 LUT
//        节流计数 16→32 位（TOP 只到 19）       ≈ +16 FF（opt_rtl 常数裁剪后应为 0）
//      合计 ≈ +25 LUT / +1~17 FF，相对 PH1P35（约 33k LUT4）可忽略。
//      ⚠ 以上是**估算**，不是 TD 实测；本次交付未跑综合/布局布线。
//  ---------------------------------------------------------------------------
//  【七、编码规范】Verilog-2001，单文件单模块；无 function/task/fork/wait/force/#delay；
//  无用户 latch（组合逻辑全部用 assign，时序全部用带复位的 always）；
//  低有效异步复位；一个 always 只干一件事；initial 初值与复位分支逐一相同。
//  参数范围：IMG_WIDTH/IMG_HEIGHT ≥ 2；MIN_PIX ≥ 1；
//            BEEP_GAP_FRAMES ≥ 1（节流计数与 GAP_TOP 都是 32 位，不会截断）；
//            BEEP_ON_CYCLES ≥ 1。
//==============================================================================

module ext_ctrl #(
    // ---- 画面尺寸：决定象限分界线（= 尺寸的一半）----
    parameter integer IMG_WIDTH       = 1280,      // 像素列数，分界 = 640
    parameter integer IMG_HEIGHT      = 720,       // 像素行数，分界 = 360
    // ---- 目标判据 ----
    parameter integer MIN_PIX         = 1,         // 命中像素数下限（1 = 与 bbox_valid 等价）
    // ---- 蜂鸣器节流参数 ----
    parameter integer BEEP_GAP_FRAMES = 20,        // 持续有目标时每 N 帧触发一次 beep（≥1）
    parameter integer BEEP_ON_CYCLES  = 400000,    // 每次 beep 包络长度（拍）；60MHz → 6.67ms
    // ⚠⚠ 蜂鸣器极性：**这个默认值 1'b0 不是板级值！**
    //   板上 Q9 = PNP9012 高边驱动（VCC_3V3 → Q9 → R38 15R → LS1 → GND，
    //   基极经 R33 2K2 到 BUZZER）⇒ 基极拉低才导通 ⇒ **低有效**。
    //   所以 `design_top_wrapper.v` 里**显式传** .BUZZ_ACT_LOW(1'b1)。
    //
    //   这里**故意**保留默认 1'b0（= 高有效）：两个 TB
    //   （`sim\tb_ext_ctrl.v` / `sim\tb_ext_ctrl_flicker.v`）都按"不覆盖 parameter"例化，
    //   它们的 checker 期望（A2/A5/A7/A8、F2/F8）也是按高有效推出来的。
    //   改默认值会连带打破那 4 条以上断言 —— 属于动已验收的验证链，不值得。
    //   （2026-09-24 决定：只加这条注释，**不改默认值**。）
    //
    //   → 写新 TB 时：要么显式传 1'b1 与板级一致，要么明确知道自己在验高有效语义。
    parameter         BUZZ_ACT_LOW    = 1'b0       // 1 = 低有效（**板级必须显式传 1**，见上）
)(
    input  wire         I_clk,
    input  wire         I_rst_n,
    // ---- 帧同步：每帧恰好 1 拍的脉冲（板级接 isp_top 的 O_tuser）----
    input  wire         I_frame,
    // ---- alg_top 的帧级检测结果 ----
    input  wire [10:0]  I_bbox_x0,      // 包围盒左边界（像素列 0..1279）
    input  wire [10:0]  I_bbox_x1,      // 包围盒右边界
    input  wire [10:0]  I_bbox_y0,      // 包围盒上边界（像素行 0..719）
    input  wire [10:0]  I_bbox_y1,      // 包围盒下边界
    input  wire         I_bbox_valid,   // 本帧是否检测到目标
    input  wire [31:0]  I_pix_count,    // 本帧命中像素数
    // ---- 外部控制输出 ----
    output reg  [3:0]   O_led,          // 1-of-4 象限指示，高有效；无目标 = 0000
    output wire         O_buzzer        // 蜂鸣器（默认高有效，BUZZ_ACT_LOW 可翻转）
);

//------------------------------------------------------------------------------
// 1. 常量
//------------------------------------------------------------------------------
    localparam [10:0] X_MID  = IMG_WIDTH  / 2;      // 640：左/右分界（列）
    localparam [10:0] Y_MID  = IMG_HEIGHT / 2;      // 360：上/下分界（行）

    localparam [31:0] MIN_PIX_C = MIN_PIX;          // 转成无符号 32 位再比较
    localparam [31:0] GAP_TOP   = BEEP_GAP_FRAMES - 1;  // 32 位：大参数也不会被截断
    localparam [31:0] BEEP_TOP  = BEEP_ON_CYCLES  - 1;

//------------------------------------------------------------------------------
// 2. 帧同步脉冲的上升沿检测
//    I_frame 正常就是 1 拍脉冲，上升沿检测不改变它的时刻（同一拍就成立）；
//    万一上游给成多拍电平，这里保证一帧只锁存一次。
//------------------------------------------------------------------------------
    reg r_frame_d;

    always @ (posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n)
            r_frame_d <= 1'b0;
        else
            r_frame_d <= I_frame;
    end

    wire w_frame = I_frame & ~r_frame_d;

//------------------------------------------------------------------------------
// 3. 本帧"有目标"判据（用**当拍输入**求值，与帧锁存在同一拍使用，口径一致）
//    三条件：valid / pix_count 达标 / 包围盒不倒置（见文件头 §二）
//------------------------------------------------------------------------------
    wire w_bb_ok   = (I_bbox_x0 <= I_bbox_x1) && (I_bbox_y0 <= I_bbox_y1);
    wire w_present = I_bbox_valid & (I_pix_count >= MIN_PIX_C) & w_bb_ok;

//------------------------------------------------------------------------------
// 4. 帧级锁存：只在帧同步那一拍把 bbox / "有目标"抄进来
//    之后整帧都用这份锁存值 —— 帧内不会被上游换值打断。
//------------------------------------------------------------------------------
    reg [10:0] r_x0, r_x1, r_y0, r_y1;
    reg        r_val;

    always @ (posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            r_x0  <= 11'd0;
            r_x1  <= 11'd0;
            r_y0  <= 11'd0;
            r_y1  <= 11'd0;
            r_val <= 1'b0;
        end else if (w_frame) begin
            r_x0  <= I_bbox_x0;
            r_x1  <= I_bbox_x1;
            r_y0  <= I_bbox_y0;
            r_y1  <= I_bbox_y1;
            r_val <= w_present;
        end
    end

//------------------------------------------------------------------------------
// 5. 象限译码（只读锁存值）
//    中心 = (min + max) / 2 向下取整；分界线上算"右/下"。
//    "floor + 严格小于" ≡ "用真实中心比较" 的证明见文件头 §五。
//    链路 = 12 位加法 → 取 bit[11:1] → 11 位比较 → 打一拍，全在帧率上跑。
//------------------------------------------------------------------------------
    wire [11:0] w_sum_x = {1'b0, r_x0} + {1'b0, r_x1};
    wire [11:0] w_sum_y = {1'b0, r_y0} + {1'b0, r_y1};

    wire [10:0] w_cx = w_sum_x[11:1];               // 目标中心列
    wire [10:0] w_cy = w_sum_y[11:1];               // 目标中心行

    wire w_left = (w_cx < X_MID);                   // 严格小于 ⇒ 中心正好 640 算"右"
    wire w_top  = (w_cy < Y_MID);                   // 严格小于 ⇒ 中心正好 360 算"下"

    always @ (posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n)
            O_led <= 4'b0000;                       // 复位：四灯全灭
        else if (!r_val)
            O_led <= 4'b0000;                       // 本帧无目标：四灯全灭
        else if (w_top &&  w_left )
            O_led <= 4'b0001;                       // 左上 → LED0
        else if (w_top && !w_left )
            O_led <= 4'b0010;                       // 右上 → LED1
        else if (!w_top &&  w_left)
            O_led <= 4'b0100;                       // 左下 → LED2
        else
            O_led <= 4'b1000;                       // 右下 → LED3
    end

//------------------------------------------------------------------------------
// 6. 蜂鸣节流（帧级决策，语义见文件头 §一）
//    · 本帧无目标             → 计数清零、不发请求
//    · 本帧有目标、上一帧没有 → **上升沿（重新检出）**：计数清零 + 立刻发请求
//    · 本帧有目标、上一帧也有 → 攒够 GAP_TOP 帧发一次请求，否则计数 +1
//    r_pres_d / r_gap_cnt / r_beep_req 放在**同一个 always**里，且 r_pres_d 在右值处
//    读到的仍是"上一帧"的值（非阻塞赋值），不存在跨 always 块的采样竞争。
//------------------------------------------------------------------------------
    reg        r_pres_d;        // 上一帧是否"有目标"
    reg [31:0] r_gap_cnt;       // 距上一次 beep 已经过的有效帧数
    reg        r_beep_req;      // 1 拍宽的 beep 请求

    always @ (posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            r_pres_d   <= 1'b0;
            r_gap_cnt  <= 32'd0;
            r_beep_req <= 1'b0;
        end else if (w_frame) begin
            r_pres_d <= w_present;
            if (!w_present) begin
                r_gap_cnt  <= 32'd0;                // 目标消失：计数重新开始
                r_beep_req <= 1'b0;
            end else if (!r_pres_d) begin
                r_gap_cnt  <= 32'd0;                // 重新检出：立刻响一次
                r_beep_req <= 1'b1;
            end else if (r_gap_cnt == GAP_TOP) begin
                r_gap_cnt  <= 32'd0;                // 持续存在：每 N 帧一次
                r_beep_req <= 1'b1;
            end else begin
                r_gap_cnt  <= r_gap_cnt + 32'd1;
                r_beep_req <= 1'b0;
            end
        end else begin
            r_beep_req <= 1'b0;                     // 请求只维持 1 拍
        end
    end

//------------------------------------------------------------------------------
// 7. beep 包络：真·不可重触发
//    `r_beep_req && !r_beep_on` —— 包络进行中到达的请求**直接丢弃**：既不重装
//    r_beep_cnt，也不把 r_beep_on 拉长，所以任何一段连续鸣叫的长度恒等于
//    BEEP_ON_CYCLES 拍，与帧周期无关。
//------------------------------------------------------------------------------
    reg [31:0] r_beep_cnt;
    reg        r_beep_on;

    always @ (posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            r_beep_cnt <= 32'd0;
            r_beep_on  <= 1'b0;
        end else if (r_beep_req && !r_beep_on) begin
            r_beep_cnt <= BEEP_TOP;                 // 只在包络空闲时装载
            r_beep_on  <= 1'b1;
        end else if (r_beep_on) begin
            if (r_beep_cnt == 32'd0)
                r_beep_on <= 1'b0;                  // 包络走完
            else
                r_beep_cnt <= r_beep_cnt - 32'd1;
        end
    end

//------------------------------------------------------------------------------
// 8. 蜂鸣器输出：包络之外还要"当前锁存帧有目标"才响 —— 目标一消失立刻静音
//------------------------------------------------------------------------------
    wire w_buzz = r_beep_on & r_val;

    assign O_buzzer = BUZZ_ACT_LOW ? ~w_buzz : w_buzz;

//------------------------------------------------------------------------------
// 9. 上电初值（仿真友好；每个寄存器的值与复位分支逐一相同）
//------------------------------------------------------------------------------
    initial begin
        r_frame_d  = 1'b0;
        r_x0       = 11'd0;
        r_x1       = 11'd0;
        r_y0       = 11'd0;
        r_y1       = 11'd0;
        r_val      = 1'b0;
        O_led      = 4'b0000;
        r_pres_d   = 1'b0;
        r_gap_cnt  = 32'd0;
        r_beep_req = 1'b0;
        r_beep_cnt = 32'd0;
        r_beep_on  = 1'b0;
    end

endmodule
