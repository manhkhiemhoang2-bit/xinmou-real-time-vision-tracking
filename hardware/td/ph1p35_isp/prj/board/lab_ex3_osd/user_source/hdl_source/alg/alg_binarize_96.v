//==============================================================================
// 文件名   : alg_binarize_96.v
// 模块名   : alg_binarize_96
// 日期     : 2026-09-14
// 版本     : v1.0
// 描述     : 96-bit 算法通道 · M2 自适应阈值二值化（3x3 窗口算子）
//
//  ---------------------------------------------------------------------------
//  【一、算法：以金标准 alg_ref.py 为准，不是以接口文档的概述为准】
//  ---------------------------------------------------------------------------
//  帧级金标准 alg_ref.py:635-641 / 逐拍模型 beat_ref.py:413-417：
//      S    = 窗口 9 点灰度和                        （0..2295，12 bit）
//      TH   = clamp( (S*57)>>9 + C_off, 0, 255 )     （local_mean，alg_ref.py:150-163）
//      b    = (center > TH)                          （**严格大于**，alg_ref.py:640）
//      out  = b ? 24'hFFFFFF : 24'h000000            （三通道填同一个值）
//  中心抽头 center = 中行·中列 = I_window[8*(4*(3*1+1)+k) +: 8]，k = 0..3。
//
//  ⚠ 两处**有意的、必须写明的**偏离/澄清（详见验证报告 §3）：
//   (1) 比较符。接口冻结文档 §2 的文字写"中心像素 >= th 出白"，但金标准
//       alg_ref.py:640 与逐拍模型 beat_ref.py:416 都是 `>`（严格大于）——
//       两份独立实现一致，按"公式以金标准为准"取 `>`。
//       差别只出现在"中心恰好等于阈值"的平坦区：`>` 出黑、`>=` 出白。
//       这不是笔误级别的差异：统一平坦块的 3x3 均值恰好等于该块的值，
//       所以平坦区整片黑白翻转，测试里专门造了平坦块盯这一条。
//   (2) `C_off` 落成 parameter（金标准 AlgPipeline.c_off 默认 0）。冻结文档 §2
//       说"留一个 I_th_off 输入口备用"，但同一条又要求三个算子**逐字相同的
//       端口表**，而表里没有 I_th_off ⇒ 不擅自加端口（加了就破坏冻结接口、
//       也会让 alg_top 的例化对不上）。改档只需在 alg_top 例化处覆盖 parameter。
//
//  ---------------------------------------------------------------------------
//  【二、延迟】全部输出相对输入**延迟 1 拍**，5 路同拍
//  ---------------------------------------------------------------------------
//  I_window 已经是 win3x3_96 延迟 2 拍的产物，本模块只允许再加 1 级：
//      组合算结果 → 同一个时钟沿装载 O_tdata / O_tvalid / O_tlast / O_tuser。
//  O_tready 是纯直通（S0-02 C-3，全链路不反压），不占延迟。
//
//  ---------------------------------------------------------------------------
//  【三、屏蔽：本模块不做】 见 S1第二批_接口冻结.md §1 铁律 2
//  ---------------------------------------------------------------------------
//  屏蔽由 alg_top 用 I_window_valid（再延迟 1 拍）统一做一次 —— 因为金标准
//  alg_ref.py:676 对**全部 6 档**无条件套屏蔽（含 M0/M1）。本模块对任何窗口
//  都吐纯算法结果，不区分 valid。I_gray_src 本档算法用不到，保留端口只为与
//  冻结接口逐字一致（alg_top 可以直接把 win3x3_96.O_tdata 接过来）。
//
//  ---------------------------------------------------------------------------
//  【四、编码规范】Verilog-2001，单文件单模块；无 function/task/fork/wait/
//  force/#delay；组合逻辑 100% 是 assign/wire ⇒ 结构上不可能出 latch；
//  时序一律 posedge + 低有效异步复位，一个 always 只干一件事。
//==============================================================================

module alg_binarize_96 #(
    parameter integer C_OFF  = 0,      // 阈值偏置；金标准默认 0（合法范围 -64..+64，步长 8）
    parameter integer TH_MIN = 0,      // 阈值下限钳位（金标准 local_mean 的 th_min）
    parameter integer TH_MAX = 255,    // 阈值上限钳位（金标准 local_mean 的 th_max，须 <= 255）
    // ★★ 2026-10-05 十一修：1=全帧均值自适应阈值（全局自适应二值化，平坦区实心、
    //   边界利落）；默认 0=3x3 局部均值原行为逐位不变（金标准/TB 零影响）。
    parameter         BIN_GLOBAL = 1'b0
)(
    input  wire         I_clk,
    input  wire         I_rst_n,
    // ---- 来自 win3x3_96（同一拍，延迟对齐）----
    input  wire         I_window_valid,   // 窗口是否可信（前 2 行 / 每行第 0 拍为 0）
    input  wire [287:0] I_window,         // 4 中心像素 × 3x3 × 8bit，索引见冻结文档 §3
    input  wire [95:0]  I_gray_src,       // 灰度已打拍的原图（本档不用，见 §三）
    input  wire [95:0]  I_rgb_center,     // 4 中心像素的 RGB888 = 图像第 y-1 行（本档不用，见 §三）
    // ---- 控制透传（与上面同拍）----
    input  wire         I_tvalid,
    input  wire         I_tlast,
    input  wire         I_tuser,
    input  wire         I_tready,
    // ---- 输出：纯算法结果，不做屏蔽 ----
    output reg  [95:0]  O_tdata,
    output reg          O_tvalid,
    output reg          O_tlast,
    output reg          O_tuser,
    output wire         O_tready
);

assign O_tready = I_tready;

//------------------------------------------------------------------------------
// 0. 编译期常量
//    C_OFF 可能为负，这里拆成"符号 + 幅值"两支，全程无符号运算 —— 避免
//    Verilog 有符号/无符号混算的坑（`unsigned < 负常数` 会被判成无符号比较）。
//------------------------------------------------------------------------------
localparam        COFF_NEG = (C_OFF < 0) ? 1'b1 : 1'b0;
localparam [7:0]  COFF_MAG = (C_OFF < 0) ? (-C_OFF) : C_OFF;   // 幅值，<= 64
localparam [8:0]  TH_LO    = TH_MIN[8:0];
localparam [8:0]  TH_HI    = TH_MAX[8:0];

//------------------------------------------------------------------------------
// 1. 窗口抽头：按冻结索引公式 tap(r,c,k) = I_window[8*(4*(3*r+c)+k) +: 8]
//    9 个 32-bit 组，组内 **byte 序号就是 k**：
//        w_tRC[8*k +: 8] = 第 k 个中心像素在 (r,c) 处的灰度
//    r = 0/1/2 → 行 y-2 / y-1 / y（y = 被装配那一拍的物理行号）
//    c = 0/1/2 → 列 4x+k-1 / 4x+k / 4x+k+1
//------------------------------------------------------------------------------
wire [31:0] w_t00 = I_window[ 31:  0];   // r=0 c=0  左上（列 4x+k-1）
wire [31:0] w_t01 = I_window[ 63: 32];   // r=0 c=1  正上
wire [31:0] w_t02 = I_window[ 95: 64];   // r=0 c=2  右上
wire [31:0] w_t10 = I_window[127: 96];   // r=1 c=0  左
wire [31:0] w_t11 = I_window[159:128];   // r=1 c=1  中心  ← 本模块的判决对象
wire [31:0] w_t12 = I_window[191:160];   // r=1 c=2  右
wire [31:0] w_t20 = I_window[223:192];   // r=2 c=0  左下
wire [31:0] w_t21 = I_window[255:224];   // r=2 c=1  正下
wire [31:0] w_t22 = I_window[287:256];   // r=2 c=2  右下

//------------------------------------------------------------------------------
// 2. 9 点求和 S（纯组合，12 bit 上下文：最大 9*255 = 2295，不溢出）
//------------------------------------------------------------------------------
wire [11:0] w_s0 = w_t00[ 7: 0] + w_t01[ 7: 0] + w_t02[ 7: 0]
                 + w_t10[ 7: 0] + w_t11[ 7: 0] + w_t12[ 7: 0]
                 + w_t20[ 7: 0] + w_t21[ 7: 0] + w_t22[ 7: 0];
wire [11:0] w_s1 = w_t00[15: 8] + w_t01[15: 8] + w_t02[15: 8]
                 + w_t10[15: 8] + w_t11[15: 8] + w_t12[15: 8]
                 + w_t20[15: 8] + w_t21[15: 8] + w_t22[15: 8];
wire [11:0] w_s2 = w_t00[23:16] + w_t01[23:16] + w_t02[23:16]
                 + w_t10[23:16] + w_t11[23:16] + w_t12[23:16]
                 + w_t20[23:16] + w_t21[23:16] + w_t22[23:16];
wire [11:0] w_s3 = w_t00[31:24] + w_t01[31:24] + w_t02[31:24]
                 + w_t10[31:24] + w_t11[31:24] + w_t12[31:24]
                 + w_t20[31:24] + w_t21[31:24] + w_t22[31:24];

//------------------------------------------------------------------------------
// 3. 局部均值 m = (S*57)>>9
//    57 = 32 + 16 + 8 + 1 ⇒ 只做常数移位与加法，零 DSP（与 gray_bt601_96 同一手法）
//    最大 2295*57 = 130815 < 2^17，所以乘积 17 bit、右移 9 位后 <= 255（8 bit）
//------------------------------------------------------------------------------
wire [16:0] w_p0 = (w_s0 << 5) + (w_s0 << 4) + (w_s0 << 3) + w_s0;
wire [16:0] w_p1 = (w_s1 << 5) + (w_s1 << 4) + (w_s1 << 3) + w_s1;
wire [16:0] w_p2 = (w_s2 << 5) + (w_s2 << 4) + (w_s2 << 3) + w_s2;
wire [16:0] w_p3 = (w_s3 << 5) + (w_s3 << 4) + (w_s3 << 3) + w_s3;

wire [7:0] w_m0 = w_p0[16:9];
wire [7:0] w_m1 = w_p1[16:9];
wire [7:0] w_m2 = w_p2[16:9];
wire [7:0] w_m3 = w_p3[16:9];

//------------------------------------------------------------------------------
// 4. TH = clamp(m + C_off, TH_MIN, TH_MAX)   —— 金标准 local_mean 逐字复刻
//    加正偏置 / 减负偏置两支都在，COFF_NEG 是常量 ⇒ 综合后只剩一支。
//    下溢在减法支里已经钳到 0；上溢由 TH_HI 比较钳住。
//------------------------------------------------------------------------------
wire [9:0] w_ma0 = {2'b00, w_m0};                       // m 抬到 10 bit（0..255）
wire [9:0] w_ma1 = {2'b00, w_m1};
wire [9:0] w_ma2 = {2'b00, w_m2};
wire [9:0] w_ma3 = {2'b00, w_m3};

wire [9:0] w_ad0 = w_ma0 + {2'b00, COFF_MAG};           // 加正偏置（<= 319）
wire [9:0] w_ad1 = w_ma1 + {2'b00, COFF_MAG};
wire [9:0] w_ad2 = w_ma2 + {2'b00, COFF_MAG};
wire [9:0] w_ad3 = w_ma3 + {2'b00, COFF_MAG};

wire [9:0] w_sb0 = (w_ma0 > {2'b00, COFF_MAG}) ? (w_ma0 - {2'b00, COFF_MAG}) : 10'd0;
wire [9:0] w_sb1 = (w_ma1 > {2'b00, COFF_MAG}) ? (w_ma1 - {2'b00, COFF_MAG}) : 10'd0;
wire [9:0] w_sb2 = (w_ma2 > {2'b00, COFF_MAG}) ? (w_ma2 - {2'b00, COFF_MAG}) : 10'd0;
wire [9:0] w_sb3 = (w_ma3 > {2'b00, COFF_MAG}) ? (w_ma3 - {2'b00, COFF_MAG}) : 10'd0;

wire [9:0] w_tr0 = COFF_NEG ? w_sb0 : w_ad0;            // 常量选择，综合后只剩一支
wire [9:0] w_tr1 = COFF_NEG ? w_sb1 : w_ad1;
wire [9:0] w_tr2 = COFF_NEG ? w_sb2 : w_ad2;
wire [9:0] w_tr3 = COFF_NEG ? w_sb3 : w_ad3;

wire [8:0] w_th0 = (w_tr0 < {1'b0, TH_LO}) ? TH_LO :
                   ((w_tr0 > {1'b0, TH_HI}) ? TH_HI : w_tr0[8:0]);
wire [8:0] w_th1 = (w_tr1 < {1'b0, TH_LO}) ? TH_LO :
                   ((w_tr1 > {1'b0, TH_HI}) ? TH_HI : w_tr1[8:0]);
wire [8:0] w_th2 = (w_tr2 < {1'b0, TH_LO}) ? TH_LO :
                   ((w_tr2 > {1'b0, TH_HI}) ? TH_HI : w_tr2[8:0]);
wire [8:0] w_th3 = (w_tr3 < {1'b0, TH_LO}) ? TH_LO :
                   ((w_tr3 > {1'b0, TH_HI}) ? TH_HI : w_tr3[8:0]);

//------------------------------------------------------------------------------
// 4.5 ★十一修：全帧均值统计（BIN_GLOBAL=1 时才是有效路径，=0 时被常量折叠裁掉）。
//   每有效拍累加 4 个中心灰度；帧首拍把上一帧总和除以常数倒数（230400 拍×4 像素
//   = 921600，1/921600 ≈ 4645/2^32，误差 <0.1%）。节拍数异常（气泡/毛刺）→ 沿用上帧均值。
//   中心灰度取 w_t11 的 byte k（窗口正中=本像素，任何拍都有定义）。
//------------------------------------------------------------------------------
wire [11:0] w_csum = {4'd0, w_t11[ 7: 0]} + {4'd0, w_t11[15: 8]}
                   + {4'd0, w_t11[23:16]} + {4'd0, w_t11[31:24]};

reg  [31:0] r_gsum;
reg  [18:0] r_gcnt;
reg  [7:0]  r_gmean;
// ⚠ 宽度陷阱：乘法必须先显式扩到 48 位再移位（32 位上下文里 >>32 会整刀清零）。
wire [47:0] w_gprod = {16'd0, r_gsum} * 48'd4645;       // ≈ sum/921600 的倒数乘法，1~2 个 DSP
wire [15:0] w_gdiv  = w_gprod[47:32];

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n) begin
        r_gsum  <= 32'd0;
        r_gcnt  <= 19'd0;
        r_gmean <= 8'd128;
    end else if (I_tvalid && I_tuser) begin            // 帧首：锁存上帧均值，本拍起新帧
        if ((r_gcnt >= 19'd230000) && (r_gcnt <= 19'd230800))
            r_gmean <= w_gdiv[7:0];
        r_gsum <= {20'd0, w_csum};
        r_gcnt <= 19'd1;
    end else if (I_tvalid) begin
        r_gsum <= r_gsum + {20'd0, w_csum};
        r_gcnt <= r_gcnt + 19'd1;
    end
end

wire [9:0] w_mag = {2'b00, r_gmean};
wire [9:0] w_ag  = w_mag + {2'b00, COFF_MAG};
wire [9:0] w_sg  = (w_mag > {2'b00, COFF_MAG}) ? (w_mag - {2'b00, COFF_MAG}) : 10'd0;
wire [9:0] w_tg  = COFF_NEG ? w_sg : w_ag;
wire [8:0] w_thg = (w_tg < {1'b0, TH_LO}) ? TH_LO :
                   ((w_tg > {1'b0, TH_HI}) ? TH_HI : w_tg[8:0]);

//------------------------------------------------------------------------------
// 5. 判决与像素拼装
//    b = (center > TH)：center 8 bit 抬成 9 bit 再比，避免宽度不等带来的歧义。
//------------------------------------------------------------------------------
// ★十二修：全局模式判决值用 3×3 盒均值 w_m0（先降噪再判）——用户实测全局阈值
//   效果好但雪花噪点重，根源是裸像素判决把噪声一起判进来了。局部模式仍判裸中心。
wire [8:0] w_dec0 = BIN_GLOBAL ? {1'b0, w_m0} : {1'b0, w_t11[ 7: 0]};
wire w_b0 = (w_dec0 > (BIN_GLOBAL ? w_thg : w_th0));
// ★十二修：全局模式判决值用 3×3 盒均值 w_m1（先降噪再判）——用户实测全局阈值
//   效果好但雪花噪点重，根源是裸像素判决把噪声一起判进来了。局部模式仍判裸中心。
wire [8:0] w_dec1 = BIN_GLOBAL ? {1'b0, w_m1} : {1'b0, w_t11[15: 8]};
wire w_b1 = (w_dec1 > (BIN_GLOBAL ? w_thg : w_th1));
// ★十二修：全局模式判决值用 3×3 盒均值 w_m2（先降噪再判）——用户实测全局阈值
//   效果好但雪花噪点重，根源是裸像素判决把噪声一起判进来了。局部模式仍判裸中心。
wire [8:0] w_dec2 = BIN_GLOBAL ? {1'b0, w_m2} : {1'b0, w_t11[23:16]};
wire w_b2 = (w_dec2 > (BIN_GLOBAL ? w_thg : w_th2));
// ★十二修：全局模式判决值用 3×3 盒均值 w_m3（先降噪再判）——用户实测全局阈值
//   效果好但雪花噪点重，根源是裸像素判决把噪声一起判进来了。局部模式仍判裸中心。
wire [8:0] w_dec3 = BIN_GLOBAL ? {1'b0, w_m3} : {1'b0, w_t11[31:24]};
wire w_b3 = (w_dec3 > (BIN_GLOBAL ? w_thg : w_th3));

wire [23:0] w_pix0 = w_b0 ? 24'hFFFFFF : 24'h000000;
wire [23:0] w_pix1 = w_b1 ? 24'hFFFFFF : 24'h000000;
wire [23:0] w_pix2 = w_b2 ? 24'hFFFFFF : 24'h000000;
wire [23:0] w_pix3 = w_b3 ? 24'hFFFFFF : 24'h000000;

// ⚠ 像素顺序：S0-02 §2.1 规定 `pix0 = I_tdata[95:72]` 是**行内最左**像素；
//    而窗口索引里 byte k 对应列 4x+k（k 越大越靠右）⇒ k=0 必须放最高位。
//    这是最容易接反的一处，验证报告 §3.3 有实测证据（接反时 M2 整拍出错）。
wire [95:0] w_result = {w_pix0, w_pix1, w_pix2, w_pix3};

//------------------------------------------------------------------------------
// 6. 输出级：5 路全在这一个时钟沿装载 ⇒ 相对输入延迟 1 拍、彼此严格同拍
//------------------------------------------------------------------------------
always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        O_tdata <= 96'd0;
    else if (I_tvalid)
        O_tdata <= w_result;
    else
        O_tdata <= 96'd0;          // C-4：输入无效拍输出全 0，不留 X
end

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        O_tvalid <= 1'b0;
    else
        O_tvalid <= I_tvalid;      // = I_tvalid 延迟 1 拍
end

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n) begin
        O_tlast <= 1'b0;
        O_tuser <= 1'b0;
    end else begin
        O_tlast <= I_tvalid && I_tlast;
        O_tuser <= I_tvalid && I_tuser;
    end
end

//------------------------------------------------------------------------------
// 7. 上电初值（仿真友好；与复位分支逐一相同）
//------------------------------------------------------------------------------
initial begin
    O_tdata  = 96'd0;
    O_tvalid = 1'b0;
    O_tlast  = 1'b0;
    O_tuser  = 1'b0;
    r_gsum   = 32'd0;
    r_gcnt   = 19'd0;
    r_gmean  = 8'd128;
end

endmodule
