//------------------------------------------------------------------------------
// 下面是 ERAM 版实现（原为独立文件；并入本文件以保证 TD 工程一定编译到它）
//------------------------------------------------------------------------------
module my_logo_rom_eram #(
    parameter LOGO_W = 288,
    parameter LOGO_H = 114,
    parameter [23:0] COLOR_FG = 24'h154B96,
    parameter [23:0] COLOR_BG = 24'h000000
)(
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire [11:0] I_dx_nx2,     // 下下一拍的段内列偏移（x_base - LOGO_X）
    input  wire [11:0] I_dy_nx2,     // 下下一拍的行偏移（y - LOGO_Y）
    output wire        O_hit0,
    output wire        O_hit1,
    output wire        O_hit2,
    output wire        O_hit3,
    output wire [23:0] O_color0,
    output wire [23:0] O_color1,
    output wire [23:0] O_color2,
    output wire [23:0] O_color3
);

localparam AW = 12;                  // 4096 字，位宽必须恰好 12（ERAM 推断硬条件）

reg [11:0] r_dx, r_dy;
always @(posedge I_clk) begin
    r_dx <= I_dx_nx2;
    r_dy <= I_dy_nx2;
end

wire        w_inrow = (r_dy < LOGO_H);
wire        w_incol = (r_dx < LOGO_W);
wire        w_ok    = w_inrow & w_incol;
wire [AW-1:0] w_addr = w_ok ? ({r_dy[6:0], 5'b0} + {7'b0, r_dx[8:4]})
                            : {AW{1'b0}};   // dy*32 + dx/16

reg [15:0] r_mem [0:4095];   //synthesis ram_style = bram
initial begin
    $readmemh("logo_tenth_4096x16.hex", r_mem);
end

reg [15:0] r_word;
always @(posedge I_clk) begin
    r_word <= r_mem[w_addr];
end

// 与 r_word 同拍：区外标志 + 段内 4 像素选择
reg        r_ok2;
reg  [1:0] r_sel;
always @(posedge I_clk) begin
    r_ok2 <= w_ok;
    r_sel <= r_dx[3:2];
end

// 注意：原实现按 MSB-first 取位：pix_seg[15 - x[3:0]]。
// 本拍 4 个像素（x 为 4 的倍数）对应 nibble 基点 = 12 - 4*x[3:2]，
// w_bits[3] = 最左像素，w_bits[0] = 最右像素。
wire [3:0] w_bits = r_word[(12 - {r_sel, 2'b00}) +: 4];

wire [3:0] w_hit = r_ok2 ? {w_bits[3], w_bits[2], w_bits[1], w_bits[0]} : 4'd0;
assign O_hit0 = w_hit[3];
assign O_hit1 = w_hit[2];
assign O_hit2 = w_hit[1];
assign O_hit3 = w_hit[0];
assign O_color0 = w_hit[3] ? COLOR_FG : COLOR_BG;
assign O_color1 = w_hit[2] ? COLOR_FG : COLOR_BG;
assign O_color2 = w_hit[1] ? COLOR_FG : COLOR_BG;
assign O_color3 = w_hit[0] ? COLOR_FG : COLOR_BG;

endmodule
