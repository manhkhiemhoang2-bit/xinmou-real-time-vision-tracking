//==============================================================================
// 文件名   : alg_m7_stable_96.v
// 模块名   : alg_m7_stable_96
// 日期     : 2026-10-05（十四修）
// 描述     : 96-bit 算法通道 · M7 掩膜帧间持续性滤波（时间 AND）
//   stable(x,y) = 本帧白(x,y) && 上一帧同位置白(x,y)
//   · 真轮廓：Sobel 边缘带宽 2~3px，帧间抖动仍落在带内 ⇒ AND 保留；
//   · 噪声散斑：帧间位置不相关 ⇒ 两帧同像素都白的概率 ≈ p² ⇒ 杀掉；
//   · 漏白横线：开轮廓的漏跑需要"连续两帧同一行都漏"才成立 ⇒ 大幅减少。
//   代价：快速移动的轮廓会滞后/断裂——M7 是风格化档，动体演示归 M6。
//
//  ---------------------------------------------------------------------------
//  【二、存储（逐条照抄 alg_framediff_96 §二 的 ERAM 纪律）】
//  单块阵列 r_mem[0:BEATS-1]，每地址 2bit = 一拍 4 像素的水平两像素对（★十五修减半，
//  v1 全分辨率 4bit/拍 让 TD 映射 57 块、总量 115/108 爆 PHY-9013）。
//    ① 地址位宽 = ceil(log2(深度))；② 读数据寄存器 r_q 直连阵列、中间无运算；
//    ③ 阵列不给复位值/初值；④ 读地址领先写地址 1 拍 ⇒ 同拍无读写冲突，
//      不依赖 read-during-write 语义；⑤ ram_style 用注释形式。
//  首帧：阵列内容不可知（硬件上电同口径）⇒ 第一帧输出无意义，第二帧起真判决。
//  行尾读地址钳回 0（不越界读 X），读到的是下一帧首拍数据，无害。
//
//  【三、延迟】数据 + 3 控制 = 1 拍，同一时钟沿装载。
//  【四、编码规范】Verilog-2001；无 function/task/#delay；组合全 assign。
//==============================================================================

module alg_m7_stable_96 #(
    parameter IMG_WIDTH  = 1280,
    parameter IMG_HEIGHT = 720
)(
    input  wire         I_clk,
    input  wire         I_rst_n,
    // ---- 输入：二值掩膜（像素 = 24'hFFFFFF 白 / 24'h000000 黑），pix0 在 [95:72] ----
    input  wire [95:0]  I_tdata,
    input  wire         I_tvalid,
    input  wire         I_tlast,     // 行末拍
    input  wire         I_tuser,     // 帧首拍
    input  wire         I_tready,
    // ---- 输出：与输入同格式，延迟 1 拍 ----
    output reg  [95:0]  O_tdata,
    output reg          O_tvalid,
    output reg          O_tlast,
    output reg          O_tuser,
    output wire         O_tready
);

localparam BEATS = (IMG_WIDTH >> 2) * IMG_HEIGHT;   // 320*720 = 230400
localparam AW    = $clog2(BEATS);                   // 18

//------------------------------------------------------------------------------
// 1. 抽头：每像素取 R 字节判白（掩膜只有 FF/00 两个合法值，判一个字节即可）。
//    ★十五修（ERAM 减半）：v1 全分辨率 4bit/拍 ⇒ TD 映射 57 块，总量 115/108 爆表
//    （PHY-9013）。改为**水平两像素一比特（OR 成对）**：帧缓冲位宽 4→2，块数≈减半；
//    副作用是好的——帧间水平抖动 1px 落在对内，AND 天然容忍，轮廓更稳。
//    bit1 = 像素对(pix0,pix1)，bit0 = 像素对(pix2,pix3)。
//------------------------------------------------------------------------------
wire [1:0] w_pair = { (I_tdata[95:88] == 8'hFF) || (I_tdata[71:64] == 8'hFF),
                      (I_tdata[47:40] == 8'hFF) || (I_tdata[23:16] == 8'hFF) };

//------------------------------------------------------------------------------
// 2. 地址：本拍写地址 = 帧内拍号；读地址 = 写地址 + 1（领先一拍）。
//    I_tuser 拍写地址强制 0（上一帧末拍留下的计数不再使用）。
//    ⚠ r_cnt 声明必须在 w_wr 之前——先用后声明=隐式线网，本工程第 N 次踩，规矩置顶。
//------------------------------------------------------------------------------
reg [AW-1:0] r_cnt;

wire [AW-1:0] w_wr = I_tuser ? {AW{1'b0}} : r_cnt;
wire [AW-1:0] w_rd = (w_wr == BEATS-1) ? {AW{1'b0}} : (w_wr + 1'b1);

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        r_cnt <= {AW{1'b0}};
    else if (I_tvalid)
        r_cnt <= I_tuser ? {{(AW-1){1'b0}},1'b1} : (w_wr + 1'b1);
end

//------------------------------------------------------------------------------
// 3. 存储阵列 + 读寄存器（无复位块，纪律②③④）——★十五修：位宽 4→2（成对）
//------------------------------------------------------------------------------
reg [1:0] r_mem [0:BEATS-1];   //synthesis ram_style = bram
reg [1:0] r_q;

always @ (posedge I_clk) begin
    if (I_tvalid) begin
        r_mem[w_wr] <= w_pair;             // 写本帧
        r_q         <= r_mem[w_rd];        // 预读下一拍的上一帧内容
    end
end

//------------------------------------------------------------------------------
// 4. 输出级（延迟 1 拍）：本拍输入 AND 上一拍预读的"上一帧同位置"。
//    非阻塞语义 ⇒ 边沿上 r_q 取的是本拍可见值（= 上一拍装载）✓ 对齐。
//    展开：对内两像素同判（水平 2px 块，填充/膨胀本来就是 2~3px 宽，无感）。
//------------------------------------------------------------------------------
wire [1:0] w_stab = w_pair & r_q;

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n) begin
        O_tdata  <= 96'd0;
        O_tvalid <= 1'b0;
        O_tlast  <= 1'b0;
        O_tuser  <= 1'b0;
    end else begin
        O_tvalid <= I_tvalid;
        O_tlast  <= I_tvalid && I_tlast;
        O_tuser  <= I_tvalid && I_tuser;
        O_tdata  <= { w_stab[1] ? 24'hFFFFFF : 24'h000000,   // pix0 ┐ 同一对
                      w_stab[1] ? 24'hFFFFFF : 24'h000000,   // pix1 ┘
                      w_stab[0] ? 24'hFFFFFF : 24'h000000,   // pix2 ┐ 同一对
                      w_stab[0] ? 24'hFFFFFF : 24'h000000 }; // pix3 ┘
    end
end

assign O_tready = I_tready;

//------------------------------------------------------------------------------
// 5. 仿真初值（阵列本体不给，纪律③；只给读寄存器，避免首拍 X 扩散）
//------------------------------------------------------------------------------
initial begin
    O_tdata  = 96'd0;
    O_tvalid = 1'b0;
    O_tlast  = 1'b0;
    O_tuser  = 1'b0;
    r_cnt    = {AW{1'b0}};
    r_q      = 2'd0;
end

endmodule
