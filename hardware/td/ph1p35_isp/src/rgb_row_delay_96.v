//==============================================================================
// 文件名   : rgb_row_delay_96.v
// 模块名   : rgb_row_delay_96
// 日期     : 2026-09-14
// 版本     : v1.1（结构定稿：单条 99bit 阵列；两阵列拆分方案已实测否决）
// 描述     : 96-bit AXI4-Stream 算法通道 · 1 行 RGB 延迟线（M3 边缘提亮取 src 用）
//
//  接口：S1第二批_接口冻结.md §5（端口逐字照抄）。
//  功能：把 96 位彩色流**延迟一整行 = BEATS_PER_LINE = 320 拍**。
//        级联意义：M3 的窗口底行是第 y 行时，本模块输出的是第 y-1 行 —— 正是
//        3×3 窗口的中心行，也就是 alg_ref 里 `src`（被提亮的那个彩色像素）所在行。
//
//  ---------------------------------------------------------------------------
//  【一、为什么延迟正好是 320 拍（推导，不是凑出来的）】
//  ---------------------------------------------------------------------------
//  320 深循环阵列，写地址 = 当前拍号 x_grp，读地址 = x_grp + 2 (mod 320)。
//  记号：state(c) 是"第 c 拍期间"的寄存器值；寄存器在第 c 拍末的 posedge 装载，
//        所以 state(c+1) 由 state(c) 与第 c 拍的输入决定。
//
//    · 写：第 c 拍末把 word(c) 写进 mem[x_grp(c)]。
//    · 读：r_q(c+1) = mem_c[x_grp(c)+2]，其中 mem_c 是第 c 拍期间的阵列内容
//      （只含 ≤ c-1 拍的写入）。
//    · x_grp 每拍 +1、周期 320 ⇒ x_grp(c-318) == x_grp(c)+2 (mod 320)，
//      且 c-318 正是"同一地址上一次被写"的那一拍。
//      ⇒ r_q(c+1) = word(c-318) ⇒ r_q(c) = word(c-319)  （阵列+读寄存器 = 319 拍）
//    · 输出级再打一拍：O(c+1) = r_q(c) ⇒ **O(c) = word(c-320)**，正好 320 拍。
//  两个地址恒差 2，永不相等 ⇒ 同一拍内不存在读写冲突，不依赖 read-during-write 语义。
//
//  ---------------------------------------------------------------------------
//  【二、控制线为什么和数据装在同一个阵列字里（附两方案的实测对比）】
//  ---------------------------------------------------------------------------
//  I_tvalid / I_tlast / I_tuser 必须和数据**同拍同源**地出阵列，否则四路输出会错位。
//  阵列字 = {I_tvalid, I_tlast, I_tuser, I_tdata} = 99 bit，一次读写全搞定，
//  结构上不可能错位，也不需要额外的 320 位移位链（那要 960 个触发器）。
//
//  两个方案都上过 TD（PH1P35MDG324，report_area 的真数字）：
//    · A：单条 99 bit 阵列（本文件）                       → #eram 3 / #dram lut 0
//    · B：拆成"数据 96 bit + 控制 3 bit"两条阵列（同址同步读写）
//                                                          → #eram 3 / #dram lut 0
//  B 没有省下任何一块 ERAM（#lut 54 / #reg 217 / #slice 83 三项也逐项相同），
//  所以按"能用简单结构就别用复杂结构"取 A：读写只有一条阵列、地址只有一个来源。
//  （块数为什么是 3 而不是 1：320×99 = 31680 bit，20Kb 一块本来就要 2 块打底，
//    再加上 C-4 的清零必须在读寄存器之后再打一拍 —— 这一拍使 TD 没法把输出寄存器
//    吸收进 ERAM 块。想省块就只能把 O_* 改成 wire（端口表 §5 写的是 output reg），
//    不值得为 2 块 ERAM 去动冻结接口，故不改。）
//
//  ---------------------------------------------------------------------------
//  【三、ERAM 硬规则（S1第二批_接口冻结.md §6，逐条落实）】
//  ---------------------------------------------------------------------------
//  ① 读地址位宽必须**刚好**等于阵列深度的位宽：
//         localparam XW = $clog2(BEATS_PER_LINE);   // 320 → 9
//     读地址 wire、写地址寄存器全部 [XW-1:0]。多给一位（11 位）TD 就拒绝 ERAM，
//     整块掉进 DRAM(LUT)（实测 #eram 0 / #dram lut 512；9 位 → #eram 2 / #dram lut 0）。
//     注意**只有读口管用**：只截写地址无效，截到 10 位也不行。详见
//     prj/_eram_check/ERAM根因定位报告.md。
//  ② 读数据寄存器直连阵列：`r_q <= r_mem[w_rd_addr];` 中间没有任何运算
//     （输出级的 C-4 清零在 r_q **之后**，不碰这条纪律）。
//  ③ 本模块只有一条阵列，不存在"两条 RAM 输出先运算再打拍"的问题。
//  ④ 阵列上**没有复位循环、没有 initial**（阵列在无复位分支的 always 里读写）。
//  ⑤ ram_style 写成注释形式 `//synthesis ram_style = bram`（安路自家 IP 的写法）。
//  ⑥ 验证只看 report_area 的 #eram / #dram lut，不看日志的 "Inferred N RAMs"。
//
//  ---------------------------------------------------------------------------
//  【四、合同（2026-09-14 定稿）：延迟 BEATS_PER_LINE 个**有效拍**；
//        输入停止时**不再吐字**（排空尾巴不存在）—— 这是与 win3x3_96 对齐所必需的】
//  ---------------------------------------------------------------------------
//  地址计数器、写口、读口**全部按 I_tvalid 门控**（见 §5/§6），所以含气泡时延迟
//  依然是严格的 320 个**有效拍**，与配对件 win3x3_96 的行缓存同拍。
//
//  C1 内容：把"输出呈现的字"按呈现先后排成字序 P，则 P[k] 与输入第 k 个有效拍
//           逐位相同（tdata/tlast/tuser 三路，三者与数据同装一个阵列字，见 §二）。
//  C2 时间：第 k 个输出字出现在第 k 个输入有效拍之后**恰好 320 拍**
//           （输入连续时 = +320 个时钟；含气泡时以有效拍为准）。
//  C3 无排空尾巴：|P| == N_in − (BPL − 2) 恰好成立。输入停止时阵列里还有
//           BPL−RD_ADV = 318 个字**没被读出**，它们**永远不出现**在输出上；
//           只有已经进入两级输出寄存器（r_q 与 O_*）的最后 2 个字会照常呈现。
//           旧版（按时钟计数）会把 318 个字全部"排空"出来 —— 那是错的：配对件
//           win3x3_96 的行缓存在输入停止时同样冻结（读口也在 if (I_tvalid) 里），
//           两者必须**同时**停，否则彩色 src 行会比灰度窗口多走一段。
//  C4 停止即冻结：最后一个输出字呈现之后，O_tdata 一路保持同一个值到仿真结束。
//
//  实测（sim\dump_rd.txt，1920 个输入有效拍）：|P| = 1602 = 1920 − 318；
//  首字在拍 324 = 4 + 320；末字在拍 1925；之后 359 拍字恒定不变。
//  实测证据与判据：sim\check_row_delay.py（C1/C2/C3/C4）；
//  真 RTL 变异自证：sim\rtl_mutation_row_delay.py 的 M1 把本模块退回旧时钟语义，
//  实测 |P| 变成 1920、318 个尾字泄漏到输出、末字之后还有 41 拍在变 —— 判据报红。
//
//  I_tvalid 延迟后为 0 的拍，O_tdata 按 C-4 清零（不让"不是数据"的东西冒充数据）。
//  ⚠ 停顿期间读数据寄存器 r_q 冻住、O_tvalid 保持为 1（阵列里存的是"有效拍序列"，
//    停顿不占字），所以本模块的 O_tvalid 是"当前正呈现一个有效字"的电平，不是
//    "输入 valid 延迟 320 拍"的逐拍复制；唯一消费者 alg_top 只取 O_tdata。
//
//  ⚠⚠ 本模块**没有流结束检测**（没有 flush、没有 idle 判定），这是"停顿必须不可见"
//    的必然代价：模块无法区分"行间行消隐停顿"和"流结束"。因此：
//      · 输入停止后"不再吐字"表现为**字冻结 + O_tvalid 电平保持**（不是 O_tvalid
//        掉 0）—— 判据必须按"有没有新字被吐出来"判，不能按 tvalid 计数判；
//        实测 O_tvalid=1 共 1961 拍（末字之后 359 拍是保持电平，其中新字 0 个）。
//      · 尾部那 318 个字是**被截断**而不是"还没吐完"：这是有效拍语义的必然结果，
//        不是缺陷（真实链路里输入流不会停，行消隐只是停顿）。
//  ⚠ 本 §四 是**纯注释改动**（2026-09-14 只改文件头 + §6 注释）：逻辑指纹
//    （去注释去空行后逐字节）与改前相同，由 sim\_logic_fingerprint.py 实测。
//
//  【五、编码规范】Verilog-2001，单文件单模块；无 function/task/fork/wait/force/
//  #delay；无 latch；一个 always 只干一件事；低有效异步复位（存储器除外）。
//==============================================================================

module rgb_row_delay_96 #(
    parameter IMG_WIDTH = 1280
)(
    input  wire         I_clk,
    input  wire         I_rst_n,
    input  wire [95:0]  I_tdata,
    input  wire         I_tvalid,
    input  wire         I_tlast,
    input  wire         I_tuser,
    input  wire         I_tready,
    output reg  [95:0]  O_tdata,      // 延迟 1 行（= 320 拍）
    output reg          O_tvalid,
    output reg          O_tlast,
    output reg          O_tuser,
    output wire         O_tready
);

//------------------------------------------------------------------------------
// 1. 常量与 tready 直通
//------------------------------------------------------------------------------
localparam BEATS_PER_LINE = IMG_WIDTH >> 2;                 // 1280 >> 2 = 320
// ⚠ XW 必须**刚好**是 ceil(log2(BEATS_PER_LINE))：320 → 9。见文件头 §三①。
localparam XW = $clog2(BEATS_PER_LINE);                     // 9
localparam [XW-1:0] LAST_BEAT = BEATS_PER_LINE - 1;         // 319
// 读地址 = x_grp + 2 (mod 320)。下面两个常量只服务于这次取模（避免用 10 位中间量
// 去比深度，位宽上出任何岔子都会让 TD 放弃 ERAM）。
localparam [XW-1:0] RD_NO_WRAP = BEATS_PER_LINE - 3;        // 317：≤ 它时 +2 不回绕
localparam [XW-1:0] RD_WRAP_SUB = BEATS_PER_LINE - 2;       // 318：> 它时 -318 回绕

assign O_tready = I_tready;                                 // C-3：全链路不反压

//------------------------------------------------------------------------------
// 2. 寄存器声明
//------------------------------------------------------------------------------
reg [XW-1:0] r_x_grp;                 // 拍计数器 0..319（= 行内拍号，不是像素计数器）
reg [98:0]   r_q;                     // 阵列读数据寄存器（直连阵列，见 §三②）

//------------------------------------------------------------------------------
// 3. 行缓冲区阵列（320 拍 × {tvalid,tlast,tuser,tdata}）
//    ⚠ 绝不在复位里清零、绝不给 initial 值（§三④）。
//------------------------------------------------------------------------------
reg [98:0] r_mem [0:BEATS_PER_LINE-1];   //synthesis ram_style = bram

//------------------------------------------------------------------------------
// 4. 组合：写数据与读地址
//------------------------------------------------------------------------------
wire [98:0] w_wr_word = {I_tvalid, I_tlast, I_tuser, I_tdata};

// 读地址领先写地址 2（见文件头 §一）：地址位宽恒为 XW，取模用 XW 位常量完成
wire [XW-1:0] w_rd_addr = (r_x_grp <= RD_NO_WRAP) ? (r_x_grp + 2'd2)
                                                  : (r_x_grp - RD_WRAP_SUB);

//------------------------------------------------------------------------------
// 5. 阵列本体：写 + 同步读（同一个 always：这是同一条 RAM 的写口与读口）
//    没有复位分支、没有 initial。写口**和读口**都按 I_tvalid 使能 —— 阵列里存的是
//    **有效拍的序列**，不是时钟序列（理由见 §6）。
//
//    ⚠⚠ 读口必须与写口/计数器同一个门控（2026-09-14 气泡测试第二轮修正）。
//    只门控写口与计数器、读口自由跑，会在每个停顿后产生**读数据寄存器提前 2 拍
//    且重复输出**的错位：停顿期间 r_x_grp 冻住 ⇒ w_rd_addr 冻在 x_grp+2 ⇒ r_q 每个
//    时钟都被重新装载成**同一个未来字**，于是 ① 停顿结束后的头几拍 O_tdata 比正确
//    值超前 2 拍，② 同一个字被连吐多拍。alg_top 的 M3 正是拿 O_tdata 当 src，实测
//    含气泡激励下 M3 帧（第 3/6 帧）每行第一个非掩蔽拍（列 4..7）输出错位。
//    门控之后"一拍"= 一个有效拍，与配对件 win3x3_96 的行缓存（读口也在
//    `if (I_tvalid)` 里）时间基准完全一致。
//------------------------------------------------------------------------------
always @ (posedge I_clk) begin
    if (I_tvalid) begin
        r_mem[r_x_grp] <= w_wr_word;
        r_q <= r_mem[w_rd_addr];
    end
end

//------------------------------------------------------------------------------
// 6. 拍号推进（0..BPL-1 循环；tuser 把拍号钉回行首）
//
//    ⚠⚠ 必须按 **I_tvalid** 门控（2026-09-14 气泡测试修正）。
//    这条延迟线是 `win3x3_96` 行缓存的**配对件**：后者按有效拍寻址。若这里按时钟
//    计数，输入每停顿一拍，彩色就相对灰度窗口多走一格 —— 实测含气泡激励下 M2/M3
//    出现彩色横向错位（拍 209：ref 90ffbc / got 90bcff），M5 的 bbox 跟着偏 2 列。
//    原注释写的"延迟 320 拍是时钟拍数、与有效与否无关"是把『拍』当成了时钟，
//    与配对件的时间基准不一致；C-2 的"无气泡"只是让两者在无气泡时恰好重合。
//    改成按有效拍计数后：无气泡时计数器逐拍行为不变（既有验证一字不动），
//    有气泡时"一行"的定义才与窗口模块一致。
//------------------------------------------------------------------------------
always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        r_x_grp <= {XW{1'b0}};
    else if (I_tvalid) begin
        if (I_tuser)
            r_x_grp <= {{(XW-1){1'b0}}, 1'b1};  // 本拍就是第 0 拍，下一拍是第 1 拍
        else if (r_x_grp == LAST_BEAT)
            r_x_grp <= {XW{1'b0}};              // 行末回绕
        else
            r_x_grp <= r_x_grp + 1'b1;
    end
end

//------------------------------------------------------------------------------
// 7. 输出级（第 2 级：阵列读寄存器之后的唯一一级 ⇒ 总延迟 320 拍）
//------------------------------------------------------------------------------
always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        O_tdata <= 96'd0;
    else if (r_q[98])
        O_tdata <= r_q[95:0];
    else
        O_tdata <= 96'd0;                        // C-4：延迟后 tvalid=0 的拍输出清零
end

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        O_tvalid <= 1'b0;
    else
        O_tvalid <= r_q[98];                     // = I_tvalid 延迟 320 拍
end

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n) begin
        O_tlast <= 1'b0;
        O_tuser <= 1'b0;
    end else begin
        O_tlast <= r_q[97];                      // = I_tlast 延迟 320 拍
        O_tuser <= r_q[96];                      // = I_tuser 延迟 320 拍
    end
end

//------------------------------------------------------------------------------
// 8. 上电初值（仿真友好；与复位分支逐一相同）
//    被**有意省略**的是阵列 r_mem 与读数据寄存器 r_q：
//      · 阵列不能有复位/初值（§三④，否则退化成 slice 寄存器）；
//      · r_q 的值直接来自阵列，给它初值也改不了"阵列本身是 X"，留着 X 反而能证明
//        输出级确实没有把未初始化内容漏出去（前 320 拍 X、324 拍起全确定）。
//------------------------------------------------------------------------------
initial begin
    r_x_grp  = {XW{1'b0}};
    O_tdata  = 96'd0;
    O_tvalid = 1'b0;
    O_tlast  = 1'b0;
    O_tuser  = 1'b0;
end

endmodule
