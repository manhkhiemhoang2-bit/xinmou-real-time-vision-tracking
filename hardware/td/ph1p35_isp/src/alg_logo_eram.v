// 文件名   : alg_logo_eram.v
// 模块名   : alg_logo_eram
// 日期     : 2026-09-17
// 版本     : v1.0
// 描述     : 安路官方 Logo 的「一拍读 4 像素」ERAM 版本（比赛基础要求 (4)）
//
//  ---------------------------------------------------------------------------
//  【一、为什么需要这个模块（G1 返工，2026-09-17）】
//  ---------------------------------------------------------------------------
//  最初的做法是把官方 anlogic_logo_rom.v（6387 条 case 的**组合**译码器）直接例化
//  4 份（一拍 4 像素）。TD 实测：
//      单份  #lut 3143 / #slice 2559 / #eram 0     （prj\logo_ab\logo_a_full160\area.txt）
//  ⇒ 4 份 ≈ 10236 slice，而器件只有 21216 slice、板级工程已用 13891 ---- **放不下**。
//  面积由**案例条数**决定，与输出位宽关系不大 ⇒ 降色深、降分辨率都救不了。
//
//  改成存储器：160x160 按 4 像素/字打包 = 6400 字 x 24 bit（6 bit/像素 x 4 像素），
//  实测 6400x24 的推断 RAM 只吃 #eram 8 / #lut 20 / #slice 20
//      （prj\_eram_init_check\logo_mem24.area）
//  ⇒ 用 8 块 ERAM（器件共 108 块）换掉约 10236 slice。**一拍只读一次**，
//    读出 24 bit 再切给 4 个 lane，各自过一次 64 色调色板（case 查表）。
//
//  ---------------------------------------------------------------------------
//  【二、打包口径（三处必须一字不差：hex 生成脚本 / 本文件 / Python 参考模型）】
//  ---------------------------------------------------------------------------
//      word = idx0 | (idx1 << 6) | (idx2 << 12) | (idx3 << 18)
//      idx0 = 该字**最左**像素（列 4*g+0） … idx3 = 最右（列 4*g+3）
//      地址 = y*40 + x_grp          y = 0..159，x_grp = 0..39
//      idx = 0 ⇒ **透明**（该像素保持原像素）；idx = 1..63 ⇒ 调色板下标
//      hex：6400 行，每行 6 个十六进制字符（logo_64c.hex），由 $readmemh 读入
//  生成脚本：sim\gen_logo_eram.py（同目录还有 logo_64c.stats.txt = 量化误差台账）
//
//  ---------------------------------------------------------------------------
//  【三、延迟契约（本项目在"数据/控制差一拍"上出过事故，务必按这里读）】
//  ---------------------------------------------------------------------------
//      ERAM 读 = 「地址进 → **下一拍**数据出」（TD 推断 ERAM 的硬条件，见 §四①）。
//      所以本模块的契约是：
//          第 T 拍给出**第 T+1 拍那 4 个像素**的坐标 (I_x_base_nx, I_y_nx)，
//          第 T+1 拍 O_hit*/O_col* 才有效 —— 即对"它所描述的那一拍"延迟正好 1 拍。
//      调用方必须把坐标**提前一拍**送进来（osd_mixer 用 w_x_nx1/w_y_nx1 完成），
//      否则安路 Logo 整面右移 4 像素。这条由 TB 的逐像素 bit 比对钉死：
//      偏一拍会立刻大面积失配（check_anlogo.py 的 A1/A2/A4/A5）。
//
//  ---------------------------------------------------------------------------
//  【四、ERAM 推断硬规则（照抄 win3x3_96.v / rgb_row_delay_96.v 的写法）】
//  ---------------------------------------------------------------------------
//      ① 读地址位宽必须**恰好** $clog2(深度) = 13 位。多给一位 TD 就拒绝 ERAM，
//         整块掉进 DRAM(LUT)（本工程实测：11 位 → #eram 0 / #dram lut 512）。
//      ② 读数据寄存器**直连**阵列：`r_word <= r_mem[w_word_addr];` 中间不许有任何运算。
//      ③ 阵列上**没有复位、没有初值寄存器**（唯一的"初值"是 $readmemh，实测被 TD
//         吃进 ERAM 初值：prj\_eram_init_check）。给 ERAM 加复位循环会把它退化成
//         slice 寄存器 —— 这是本工程铁律。
//      ④ ram_style 写成注释形式 `//synthesis ram_style = bram`（安路自家 IP 的写法）。
//      ⑤ 验证只看 report_area 的 #eram / #dram lut，不看日志的 "Inferred N RAMs"。
//
//  ---------------------------------------------------------------------------
//  【五、配置约束（有仿真护栏）】
//  ---------------------------------------------------------------------------
//      **ANLOGO_X 必须是 4 的倍数**（4px/字 对齐的前提）：x_base = 4*x_grp 恒为 4 的
//      倍数，若 ANLOGO_X 不是 4 的倍数，字地址 (x_base-ANLOGO_X)/4 就会错位，整幅花掉。
//      osd_mixer 侧有仿真护栏 r_an_cfg_err（$display 报错 + TB 断言），ANLOGO_Y 无要求。
//
//  ---------------------------------------------------------------------------
//  【六、颜色（量化误差有台账，见 §七）】
//  ---------------------------------------------------------------------------
//      官方素材 6387 个不透明像素 / 579 种颜色 → 中位切分量化到 **63 色 + index0 透明**。
//      误差（6387 个命中像素，每通道）：max 20 / mean 0.62 / >16 的像素 7 个（0.11%）。
//      对照 16 色（4bpp，只省 1 块 ERAM）：max 47 / mean 1.68 / >16 的 182 个（2.85%）
//      ⇒ 选 64 色：多花 1 块 ERAM（8/108）换掉 1/16 的色阶损失不值当省。
//      调色板 63 x 24bit 直接写在下面的 case 里（每 lane 约 24 个 LUT6），不单独占 ERAM。
//
//  ---------------------------------------------------------------------------
//  【七、没做的事 / 已知限制】
//  ---------------------------------------------------------------------------
//  1. 一拍只读一次 ⇒ 安路 Logo 的列位置必须 4 像素对齐（ANLOGO_X % 4 == 0），
//     不能像逐像素查表那样任意摆放。本设计固定在左上角 (0,0)，满足要求。
//  2. 6 bit/像素是有损量化（误差台账见上），不是逐 bit 还原官方素材。
//     这是**面积换精度**的自觉取舍，误差界由 check_anlogo.py 独立复算并断言。
//  3. hex 用相对路径 $readmemh("logo_64c.hex")：path 按**综合时的 CWD** 解析，
//     所以 hex 同时放在 td_project\、prj\_fullchip\、hdl_source\alg\、src\ 四处（内容一致）。
//==============================================================================
`timescale 1ns / 1ps

module alg_logo_eram #(
    // ---- 安路 Logo 左上角。ANLOGO_X **必须**是 4 的倍数（§五）----
    parameter ANLOGO_X = 0,
    parameter ANLOGO_Y = 0
)(
    input  wire        I_clk,
    input  wire        I_rst_n,
    // ---- 下一拍上台那 4 个像素的坐标（**不是本拍**，见 §三）----
    input  wire [10:0] I_x_base_nx,   // 那 4 个像素最左列的绝对列号（4 的倍数）
    input  wire [10:0] I_y_nx,        // 那一拍的行号
    // ---- 输出：与 I_*_nx 描述的那一拍同拍有效 ----
    output wire        O_hit0,
    output wire        O_hit1,
    output wire        O_hit2,
    output wire        O_hit3,
    output wire [23:0] O_col0,
    output wire [23:0] O_col1,
    output wire [23:0] O_col2,
    output wire [23:0] O_col3
);

localparam AN_W     = 160;                 // 素材固有宽（官方 case 按 y*160+x 编址）
localparam AN_H     = 160;
localparam AN_XG    = AN_W >> 2;           // 40 字/行
localparam AN_WORDS = AN_H * AN_XG;        // 6400 字
localparam AW       = $clog2(AN_WORDS);    // 13 —— 必须恰好 13 位（§四①）

//------------------------------------------------------------------------------
// 0b. 坐标输入打一拍（2026-09-21 时序优化）
//     原来「坐标 → 区域判断 → 行基址移位加 → 字地址 → ERAM」是一条 11 级组合链，
//     末端地址线扇出 728，是整板最差路径（余量只剩 0.258ns）。
//     在这里给坐标打一拍，把链劈成「osd 计数器 → 坐标寄存器」和
//     「坐标寄存器 → 地址 → ERAM」两段，各自变短、扇出由寄存器驱动。
//     代价：整条 Logo 通路多 1 拍延迟 ⇒ 调用方 osd_mixer 必须把坐标**再提前一拍**
//     送进来（nx1 改 nx2），输出对齐不变（osd 的逐像素 bit 比对会兜底验证）。
//------------------------------------------------------------------------------
reg [10:0] r_xn, r_yn;
always @(posedge I_clk) begin
    r_xn <= I_x_base_nx;
    r_yn <= I_y_nx;
end

//------------------------------------------------------------------------------
// 1. 区内外判据（**整拍**判定）
//    4px/字 对齐 + ANLOGO_X 是 4 的倍数 ⇒ 一拍的 4 个像素要么全在区内、要么全在区外，
//    不存在跨边界的拍。所以这里只需要拍级判据，不需要（也不可能）逐像素判据。
//    ⚠ 2026-09-21 起判据用打拍后的 r_xn/r_yn（见 §0b），不再直接用输入端口。
//------------------------------------------------------------------------------
wire        w_inrow = (r_yn >= ANLOGO_Y) && (r_yn < (ANLOGO_Y + AN_H));
wire [11:0] w_dy    = {1'b0, r_yn} - {1'b0, ANLOGO_Y};
wire        w_incol = (r_xn >= ANLOGO_X) &&
                      (r_xn < (ANLOGO_X + AN_W));
wire [11:0] w_dx    = {1'b0, r_xn} - {1'b0, ANLOGO_X};
wire        w_ok    = w_inrow && w_incol;

//------------------------------------------------------------------------------
// 2. 字地址 = dy*40 + dx/4
//    行基址写成移位加法 dy*32 + dy*8（官方那版 S_logo_y*LOGO_W 被 TD 推成 DSPMULT，
//    是官方基线最差路径的一部分，这里不给它机会）。
//    区外整拍清零：地址恒落在 0..6399，ERAM 地址线在区外不翻转。
//    ⚠ 这**不是**正确性防线 —— 正确性由 §4 的 r_ok 屏蔽保证。两重保护是有意的：
//      地址钳位是省翻转的优化，r_ok 才是"区外一个 bit 都不动"的保证。
//------------------------------------------------------------------------------
wire [AW-1:0] w_dy13      = {4'b0000, w_dy[8:0]};                    // dy ≤ 159
wire [AW-1:0] w_rowbase   = w_ok ? ((w_dy13 << 5) + (w_dy13 << 3))
                                 : {AW{1'b0}};
wire [AW-1:0] w_word_addr = w_rowbase + {{(AW-6){1'b0}}, w_dx[7:2]};

//------------------------------------------------------------------------------
// 3. ERAM 本体：只读 + $readmemh 初值。**没有复位、没有初值寄存器**（§四③）
//------------------------------------------------------------------------------
reg [23:0] r_mem [0:AN_WORDS-1];   //synthesis ram_style = bram

initial begin
    $readmemh("logo_64c.hex", r_mem);
end

reg [23:0] r_word;      // 读数据寄存器：直连阵列，中间不许有运算（§四②）
reg        r_ok;        // 该拍是否在区内 —— 与 r_word **同拍**（一起打拍）

always @ (posedge I_clk) begin
    r_word <= r_mem[w_word_addr];          // ← ERAM 读：地址进、下一拍数据出
end

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        r_ok <= 1'b0;
    else
        r_ok <= w_ok;                      // 与 r_word 同拍，不能少这一级
end

//------------------------------------------------------------------------------
// 4. 逐 lane 取 index + 透明判据
//    透明 = index 0 ⇒ 该像素不算命中（保持原像素）；命中还必须通过区外屏蔽 r_ok。
//------------------------------------------------------------------------------
wire [5:0] w_idx0 = r_word[5:0];           // 最左像素（列 4*g+0）
wire [5:0] w_idx1 = r_word[11:6];
wire [5:0] w_idx2 = r_word[17:12];
wire [5:0] w_idx3 = r_word[23:18];         // 最右像素（列 4*g+3）

assign O_hit0 = r_ok && (w_idx0 != 6'd0);
assign O_hit1 = r_ok && (w_idx1 != 6'd0);
assign O_hit2 = r_ok && (w_idx2 != 6'd0);
assign O_hit3 = r_ok && (w_idx3 != 6'd0);

