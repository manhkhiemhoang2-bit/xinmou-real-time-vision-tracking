//==============================================================================
// 文件名   : alg_smooth_96.v
// 模块名   : alg_smooth_96
// 日期     : 2026-09-14
// 版本     : v1.0
// 描述     : 96-bit 算法通道 · M4 高斯 1-2-1 平滑（3x3 窗口算子）
//
//  ---------------------------------------------------------------------------
//  【一、算法：以金标准 alg_ref.py 为准】
//  ---------------------------------------------------------------------------
//  帧级金标准 alg_ref.py:650-654 / 逐拍模型 beat_ref.py:426-428，
//  逐字对应 alg_ref.gauss_121（alg_ref.py:432-445）：
//      rowN = aN0 + 2*aN1 + aN2                  （N = 0/1/2，每行最大 1020，10 bit）
//      G    = (row0 + 2*row1 + row2) >> 4        （最大 4080，最后才右移 4）
//      out  = {G, G, G}                          （灰度三通道同值）
//
//  ⚠ 顺序陷阱（金标准文件里专门标了）：**必须先完成整行求和再右移 4**。
//    写成 (row0>>4) + (row1>>3) + (row2>>4) 会各丢 4 位 LSB 的精度（每项最多偏低 3），
//    这是可分离卷积最常见的实现错误，本模块用一整条表达式求和后一次移位，结构上不可能写错。
//
//  ⚠ 名字说明：规格图上的 `alg_median_96` 是**过时名字**，M4 是高斯的 1-2-1 可分离
//    平滑，不是中值滤波（冻结文档 §2 原文）。这里不实现中值。
//
//  ---------------------------------------------------------------------------
//  【二、延迟】全部输出相对输入**延迟 1 拍**，5 路同拍（同 alg_binarize_96 §二）
//  【三、屏蔽】本模块不做，由 alg_top 用 I_window_valid 统一做（同 §三 铁律 2）
//  【四、编码规范】Verilog-2001，单文件单模块；无 function/task/fork/wait/
//  force/#delay；组合全 assign/wire ⇒ 无 latch；一个 always 只干一件事。
//==============================================================================

module alg_smooth_96 #(
    parameter integer UNUSED = 0,       // 占位：保留 parameter 列表形式
    // ★十修：1=盒式均值核（平滑更强）；默认 0=121x121 原行为逐位不变。
    parameter         SMOOTH_BOX = 1'b0
)(
    input  wire         I_clk,
    input  wire         I_rst_n,
    // ---- 来自 win3x3_96（同一拍，延迟对齐）----
    input  wire         I_window_valid,   // 窗口是否可信（本模块不用，见 §三）
    input  wire [287:0] I_window,         // 4 中心像素 × 3x3 × 8bit（索引见冻结文档 §3）
    input  wire [95:0]  I_gray_src,       // 灰度已打拍的原图（本档不用）
    input  wire [95:0]  I_rgb_center,     // 4 中心像素的 RGB888 = 图像第 y-1 行（本档不用，见 §三）
    // ---- 控制透传（与上面同拍）----
    input  wire         I_tvalid,
    input  wire         I_tlast,
    input  wire         I_tuser,
    input  wire         I_tready,
    // ---- 输出：纯算法结果，不做屏蔽 ----
    output reg  [95:0]  O_tdata,
    output reg          O_tvalid,
    output reg          O_tlast,
    output reg          O_tuser,
    output wire         O_tready
);

assign O_tready = I_tready;

//------------------------------------------------------------------------------
// 1. 窗口抽头：w_tRC[8*k +: 8] = 第 k 个中心像素在 (r,c) 处的灰度
//------------------------------------------------------------------------------
wire [31:0] w_t00 = I_window[ 31:  0];   // r=0 c=0  左上（列 4x+k-1）
wire [31:0] w_t01 = I_window[ 63: 32];   // r=0 c=1  正上
wire [31:0] w_t02 = I_window[ 95: 64];   // r=0 c=2  右上
wire [31:0] w_t10 = I_window[127: 96];   // r=1 c=0  左
wire [31:0] w_t11 = I_window[159:128];   // r=1 c=1  中心
wire [31:0] w_t12 = I_window[191:160];   // r=1 c=2  右
wire [31:0] w_t20 = I_window[223:192];   // r=2 c=0  左下
wire [31:0] w_t21 = I_window[255:224];   // r=2 c=1  正下
wire [31:0] w_t22 = I_window[287:256];   // r=2 c=2  右下

//------------------------------------------------------------------------------
// 2. 三行各做 121：rowN = aN0 + 2*aN1 + aN2（10 bit，最大 4*255 = 1020）
//------------------------------------------------------------------------------
wire [9:0] w_r0_0 = w_t00[ 7: 0] + {w_t01[ 7: 0], 1'b0} + w_t02[ 7: 0];
wire [9:0] w_r1_0 = w_t10[ 7: 0] + {w_t11[ 7: 0], 1'b0} + w_t12[ 7: 0];
wire [9:0] w_r2_0 = w_t20[ 7: 0] + {w_t21[ 7: 0], 1'b0} + w_t22[ 7: 0];

wire [9:0] w_r0_1 = w_t00[15: 8] + {w_t01[15: 8], 1'b0} + w_t02[15: 8];
wire [9:0] w_r1_1 = w_t10[15: 8] + {w_t11[15: 8], 1'b0} + w_t12[15: 8];
wire [9:0] w_r2_1 = w_t20[15: 8] + {w_t21[15: 8], 1'b0} + w_t22[15: 8];

wire [9:0] w_r0_2 = w_t00[23:16] + {w_t01[23:16], 1'b0} + w_t02[23:16];
wire [9:0] w_r1_2 = w_t10[23:16] + {w_t11[23:16], 1'b0} + w_t12[23:16];
wire [9:0] w_r2_2 = w_t20[23:16] + {w_t21[23:16], 1'b0} + w_t22[23:16];

wire [9:0] w_r0_3 = w_t00[31:24] + {w_t01[31:24], 1'b0} + w_t02[31:24];
wire [9:0] w_r1_3 = w_t10[31:24] + {w_t11[31:24], 1'b0} + w_t12[31:24];
wire [9:0] w_r2_3 = w_t20[31:24] + {w_t21[31:24], 1'b0} + w_t22[31:24];

//------------------------------------------------------------------------------
// 3. 纵向 121 后 >>4：G = (row0 + 2*row1 + row2) >> 4
//    一次求和完再移位（顺序陷阱见 §一）；最大 4080 < 2^12，右移 4 位后 <= 255
//------------------------------------------------------------------------------
wire [11:0] w_s0 = (w_r0_0 + {w_r1_0, 1'b0} + w_r2_0) >> 4;
wire [11:0] w_s1 = (w_r0_1 + {w_r1_1, 1'b0} + w_r2_1) >> 4;
wire [11:0] w_s2 = (w_r0_2 + {w_r1_2, 1'b0} + w_r2_2) >> 4;
wire [11:0] w_s3 = (w_r0_3 + {w_r1_3, 1'b0} + w_r2_3) >> 4;

//------------------------------------------------------------------------------
// 2.2 ★十修：盒式均值核（9 点全 1/9，中心权重从 121 的 4/16 降到 1/9 ⇒ 平滑力度
//   约翻倍，"柔滑"肉眼可见）。×57>>9 ≈ /9，与 sobel/binarize 的 local_mean 同源写法。
//   SMOOTH_BOX=0 时综合按常量折叠裁掉本路径 ⇒ 默认行为逐位不变。
//------------------------------------------------------------------------------
wire [11:0] w_bx0 = w_t00[7:0]+w_t01[7:0]+w_t02[7:0]+w_t10[7:0]+w_t11[7:0]+w_t12[7:0]+w_t20[7:0]+w_t21[7:0]+w_t22[7:0];
wire [11:0] w_bx1 = w_t00[15:8]+w_t01[15:8]+w_t02[15:8]+w_t10[15:8]+w_t11[15:8]+w_t12[15:8]+w_t20[15:8]+w_t21[15:8]+w_t22[15:8];
wire [11:0] w_bx2 = w_t00[23:16]+w_t01[23:16]+w_t02[23:16]+w_t10[23:16]+w_t11[23:16]+w_t12[23:16]+w_t20[23:16]+w_t21[23:16]+w_t22[23:16];
wire [11:0] w_bx3 = w_t00[31:24]+w_t01[31:24]+w_t02[31:24]+w_t10[31:24]+w_t11[31:24]+w_t12[31:24]+w_t20[31:24]+w_t21[31:24]+w_t22[31:24];
// ⚠ 十三修（宽度截断 bug）：移位加法必须先落 17 位线网再取 [16:9]。
//   旧写法 ((w_bx<<5)+...)>>9 在 12 位自上下文里 <<5 直接回绕 ⇒ L 成垃圾小值 ⇒
//   delta=L-g 大负数 ⇒ 三通道齐砍、先后夹断到 0 ⇒ 画面又暗又出紫/红斑块。
//   （与 alg_sobel_96 §3 / alg_binarize_96 §3 同一正规手法。）
wire [16:0] w_bpm0 = (w_bx0 << 5) + (w_bx0 << 4) + (w_bx0 << 3) + w_bx0;
wire [16:0] w_bpm1 = (w_bx1 << 5) + (w_bx1 << 4) + (w_bx1 << 3) + w_bx1;
wire [16:0] w_bpm2 = (w_bx2 << 5) + (w_bx2 << 4) + (w_bx2 << 3) + w_bx2;
wire [16:0] w_bpm3 = (w_bx3 << 5) + (w_bx3 << 4) + (w_bx3 << 3) + w_bx3;
wire [7:0]  w_bxm0 = w_bpm0[16:9];
wire [7:0]  w_bxm1 = w_bpm1[16:9];
wire [7:0]  w_bxm2 = w_bpm2[16:9];
wire [7:0]  w_bxm3 = w_bpm3[16:9];
wire [7:0]  w_L0 = SMOOTH_BOX ? w_bxm0 : w_s0[7:0];
wire [7:0]  w_L1 = SMOOTH_BOX ? w_bxm1 : w_s1[7:0];
wire [7:0]  w_L2 = SMOOTH_BOX ? w_bxm2 : w_s2[7:0];
wire [7:0]  w_L3 = SMOOTH_BOX ? w_bxm3 : w_s3[7:0];


//------------------------------------------------------------------------------
// 2.5 ★★ 2026-10-03 五修：旧版把灰度模糊值复制成 R=G=B ⇒ 整帧灰白（用户板上投诉）。
//   改为"亮度低通、色度保色"（真实 ISP 的 Y-only 滤波常规做法）：
//     out_ch = sat8( orig_ch + (L - g) )   L=121x121 模糊灰度，g=中心像素原灰度
//   平滑量与旧版完全一致（亮度通道同样被低通），颜色不再丢。
//------------------------------------------------------------------------------
function [7:0] f_sat_add;
    input [7:0]         v;
    input signed [9:0]  d;
    reg   signed [9:0]  t;
    begin
        t = $signed({2'b00, v}) + d;
        if (t < 0)             f_sat_add = 8'd0;
        else if (t > 10'sd255) f_sat_add = 8'd255;
        else                   f_sat_add = t[7:0];
    end
endfunction

wire [23:0] w_src0 = I_rgb_center[24*3 +: 24];   // k=0（列 4x+0 在 [95:72]，同 sobel 口径）
wire [23:0] w_src1 = I_rgb_center[24*2 +: 24];
wire [23:0] w_src2 = I_rgb_center[24*1 +: 24];
wire [23:0] w_src3 = I_rgb_center[24*0 +: 24];
wire signed [9:0] w_dlt0 = $signed({2'b00, w_L0}) - $signed({2'b00, w_t11[ 7: 0]});
wire signed [9:0] w_dlt1 = $signed({2'b00, w_L1}) - $signed({2'b00, w_t11[15: 8]});
wire signed [9:0] w_dlt2 = $signed({2'b00, w_L2}) - $signed({2'b00, w_t11[23:16]});
wire signed [9:0] w_dlt3 = $signed({2'b00, w_L3}) - $signed({2'b00, w_t11[31:24]});

wire [23:0] w_pix0 = {f_sat_add(w_src0[23:16], w_dlt0), f_sat_add(w_src0[15:8], w_dlt0), f_sat_add(w_src0[7:0], w_dlt0)};
wire [23:0] w_pix1 = {f_sat_add(w_src1[23:16], w_dlt1), f_sat_add(w_src1[15:8], w_dlt1), f_sat_add(w_src1[7:0], w_dlt1)};
wire [23:0] w_pix2 = {f_sat_add(w_src2[23:16], w_dlt2), f_sat_add(w_src2[15:8], w_dlt2), f_sat_add(w_src2[7:0], w_dlt2)};
wire [23:0] w_pix3 = {f_sat_add(w_src3[23:16], w_dlt3), f_sat_add(w_src3[15:8], w_dlt3), f_sat_add(w_src3[7:0], w_dlt3)};

// ⚠ 像素顺序同 alg_binarize_96：S0-02 §2.1 规定 pix0 = [95:72] 是行内最左像素，
//    而窗口 byte k 对应列 4x+k（k 越大越靠右）⇒ k=0 必须放最高位。
wire [95:0] w_result = {w_pix0, w_pix1, w_pix2, w_pix3};

//------------------------------------------------------------------------------
// 4. 输出级：5 路同一个时钟沿装载 ⇒ 延迟 1 拍、彼此严格同拍
//------------------------------------------------------------------------------
always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        O_tdata <= 96'd0;
    else if (I_tvalid)
        O_tdata <= w_result;
    else
        O_tdata <= 96'd0;          // C-4
end

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n)
        O_tvalid <= 1'b0;
    else
        O_tvalid <= I_tvalid;
end

always @ (posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n) begin
        O_tlast <= 1'b0;
        O_tuser <= 1'b0;
    end else begin
        O_tlast <= I_tvalid && I_tlast;
        O_tuser <= I_tvalid && I_tuser;
    end
end

//------------------------------------------------------------------------------
// 5. 上电初值（仿真友好；与复位分支逐一相同）
//------------------------------------------------------------------------------
initial begin
    O_tdata  = 96'd0;
    O_tvalid = 1'b0;
    O_tlast  = 1'b0;
    O_tuser  = 1'b0;
end

endmodule
